// Scans projects/*/brief.json and writes src/projects.generated.ts so Studio
// and the renderer pick up every project. Runs automatically before dev/render.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const projectsDir = path.join(root, "projects");
const out = path.join(root, "src", "projects.generated.ts");

const SLUG = /^[a-z0-9]+(-[a-z0-9]+)*$/;

const slugs = fs
  .readdirSync(projectsDir, { withFileTypes: true })
  .filter((d) => d.isDirectory() && !d.name.startsWith("_"))
  .map((d) => d.name)
  .filter((slug) => {
    const briefFile = path.join(projectsDir, slug, "brief.json");
    if (!fs.existsSync(briefFile)) return false;
    // A JSON syntax error would break the whole bundle (every project), so leave that one out.
    try {
      JSON.parse(fs.readFileSync(briefFile, "utf8"));
    } catch (err) {
      console.warn(`⚠ Skipping "${slug}": brief.json is not valid JSON — ${err.message}`);
      return false;
    }
    if (!SLUG.test(slug)) {
      console.warn(`⚠ Skipping "${slug}": project folders must be kebab-case (a-z, 0-9, -).`);
      return false;
    }
    return true;
  })
  .sort();

// voiceover.json (from `npm run ai -- voiceover` / autopilot) drives the on-screen captions.
const hasVoiceover = (slug) => {
  const file = path.join(projectsDir, slug, "voiceover.json");
  if (!fs.existsSync(file)) return false;
  try {
    JSON.parse(fs.readFileSync(file, "utf8"));
    return true;
  } catch (err) {
    console.warn(`⚠ "${slug}": voiceover.json is not valid JSON, captions off — ${err.message}`);
    return false;
  }
};
const withVo = new Set(slugs.filter(hasVoiceover));

const lines = [
  "// AUTO-GENERATED by scripts/sync-projects.mjs — do not edit.",
  'import type { FormatKey } from "./lib/layout";',
  ...slugs.map((s, i) => `import p${i} from "../projects/${s}/brief.json";`),
  ...slugs.map((s, i) => (withVo.has(s) ? `import v${i} from "../projects/${s}/voiceover.json";` : "")).filter(Boolean),
  "",
  "export type Brief = { template: string; formats: FormatKey[]; compositionIdPrefix?: string; captions?: boolean; props: unknown };",
  "export type Voiceover = { lines: { scene: string; text: string }[]; scenes?: { scene: string }[] };",
  "",
  "export const PROJECTS: { slug: string; brief: Brief; voiceover?: Voiceover }[] = [",
  ...slugs.map((s, i) => `  { slug: "${s}", brief: p${i} as Brief${withVo.has(s) ? `, voiceover: v${i} as Voiceover` : ""} },`),
  "];",
  "",
];

const next = lines.join("\n");
const prev = fs.existsSync(out) ? fs.readFileSync(out, "utf8") : "";
if (next !== prev) fs.writeFileSync(out, next);
console.log(`✓ Synced ${slugs.length} project(s): ${slugs.join(", ") || "(none)"}`);
